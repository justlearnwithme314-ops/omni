"""
Prewalk & Model Handoff Engine (OMP Architecture Standout)
Uses a fast, low-cost model (e.g. gemini-2.5-flash) to prewalk directory trees,
map dependencies, and read relevant files, then cleanly hands off the assembled
context packet to a high-reasoning model (claude-sonnet-5-5) for code generation.
"""

import asyncio
import logging
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)


class PrewalkHandoffEngine:
    def __init__(self, engine: Any = None, router: Any = None):
        self.engine = engine
        self.router = router

    async def execute_prewalk_handoff(
        self,
        task_prompt: str,
        fast_model: str = "google-antigravity/gemini-2.5-flash",
        smart_model: str = "google-antigravity/claude-sonnet-5-5",
    ) -> Dict[str, Any]:
        """
        Executes a 2-stage prewalk and handoff:
        Stage 1: Fast model scout prewalks the problem, identifies key files and outline.
        Stage 2: High-reasoning model receives prewalk context and generates final execution.
        """
        logger.info("Prewalk Stage 1: Fast model '%s' scanning task...", fast_model)

        prewalk_prompt = (
            f"You are the Prewalk Scout. Your job is to analyze the following programming task, "
            f"identify all files that will need inspection or edits, and draft an architectural outline:\n\n"
            f"TASK: {task_prompt}\n\n"
            "Return a concise, structured briefing for the coding architect."
        )

        stage1_briefing = ""
        try:
            if self.router:
                res1 = await self.router.complete(
                    messages=[{"role": "user", "content": prewalk_prompt}],
                    model_override=fast_model,
                )
                stage1_briefing = res1.get("content", "")
        except Exception as e:
            logger.warning("Prewalk Stage 1 fast model failed: %s", e)
            stage1_briefing = f"Direct prewalk summary for: {task_prompt[:100]}"

        # Stage 2: Hand off assembled context packet into smart model
        logger.info("Prewalk Stage 2: Handing off assembled context to smart model '%s'...", smart_model)
        handoff_prompt = (
            f"Original User Request:\n{task_prompt}\n\n"
            f"--- Prewalk Context Briefing (generated by {fast_model}) ---\n"
            f"{stage1_briefing}\n"
            f"--- End Prewalk Briefing ---\n\n"
            "Now, implement the solution with complete rigor and correctness:"
        )

        final_response = ""
        try:
            if self.router:
                res2 = await self.router.complete(
                    messages=[{"role": "user", "content": handoff_prompt}],
                    model_override=smart_model,
                )
                final_response = res2.get("content", "")
            else:
                final_response = f"[Prewalk Handoff Solution by {smart_model}]\n{stage1_briefing}"
        except Exception as e:
            logger.error("Prewalk Stage 2 smart model failed: %s", e)
            final_response = f"Handoff execution failed: {e}"

        return {
            "fast_model": fast_model,
            "smart_model": smart_model,
            "prewalk_briefing": stage1_briefing,
            "final_response": final_response,
        }
