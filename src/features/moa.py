"""
Mixture-of-Agents (MoA) Multi-Model Reasoning Engine (Hermes Architecture Standout)
Orchestrates multi-layer reasoning councils:
Layer 1 (Proposers): Multiple models generate diverse candidate solutions in parallel.
Layer 2 (Synthesizer/Aggregator): A flagship model synthesizes the best insights.
"""

import asyncio
import logging
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

DEFAULT_PROPOSERS = [
    "google-antigravity/gemini-2.5-flash",
    "openai/gpt-4o-mini",
    "anthropic/claude-3-5-haiku",
]

DEFAULT_AGGREGATOR = "google-antigravity/gemini-3.8-flash"


class MixtureOfAgentsEngine:
    def __init__(self, provider_router: Any = None):
        self.router = provider_router

    async def run_moa(
        self,
        query: str,
        proposers: Optional[List[str]] = None,
        aggregator: Optional[str] = None,
        tools: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """
        Executes a 2-layer Mixture of Agents reasoning turn.
        Returns {"final_synthesis": str, "proposals": list[dict], "aggregator": str}.
        """
        active_proposers = proposers or DEFAULT_PROPOSERS
        active_aggregator = aggregator or DEFAULT_AGGREGATOR

        # Layer 1: Concurrently query all proposer models
        logger.info("MoA Layer 1: Querying %d proposer models in parallel...", len(active_proposers))

        async def _query_proposer(model_name: str) -> Dict[str, Any]:
            try:
                if self.router:
                    res = await self.router.complete(
                        messages=[{"role": "user", "content": query}],
                        tools=tools,
                        model_override=model_name,
                    )
                    return {
                        "model": model_name,
                        "status": "success",
                        "content": res.get("content", ""),
                        "tool_calls": res.get("tool_calls", []),
                    }
            except Exception as e:
                logger.warning("MoA proposer %s failed: %s", model_name, e)
                return {
                    "model": model_name,
                    "status": "error",
                    "content": f"[Error: {e}]",
                    "tool_calls": [],
                }
            return {
                "model": model_name,
                "status": "mock",
                "content": f"Candidate perspective from {model_name} on: {query[:60]}",
                "tool_calls": [],
            }

        proposals = await asyncio.gather(*[_query_proposer(m) for m in active_proposers])

        # Format Layer 1 proposals for the Layer 2 Synthesizer
        proposals_block = []
        for idx, p in enumerate(proposals):
            if p["status"] == "success" and p["content"]:
                proposals_block.append(f"### Candidate {idx+1} ({p['model']}):\n{p['content']}")
            elif p["status"] != "error":
                proposals_block.append(f"### Candidate {idx+1} ({p['model']}):\n{p['content']}")

        if not proposals_block:
            proposals_block.append("No successful proposals generated.")

        synthesis_prompt = (
            f"You are the Lead Synthesizer in a Mixture-of-Agents council.\n"
            f"Original User Request:\n{query}\n\n"
            f"Below are independent proposals generated by different AI models:\n\n"
            + "\n\n".join(proposals_block)
            + "\n\nCritically analyze each candidate solution, resolve any contradictions or flaws, "
            "and synthesize the optimal, most comprehensive and accurate response:"
        )

        # Layer 2: Synthesize with the aggregator model
        logger.info("MoA Layer 2: Synthesizing final response with aggregator %s...", active_aggregator)
        try:
            if self.router:
                synth_res = await self.router.complete(
                    messages=[{"role": "user", "content": synthesis_prompt}],
                    tools=tools,
                    model_override=active_aggregator,
                )
                final_text = synth_res.get("content", "")
            else:
                final_text = f"[MoA Synthesis by {active_aggregator}]\n" + "\n".join(f"- {p['content'][:100]}" for p in proposals)
        except Exception as e:
            logger.error("MoA synthesis failed: %s", e)
            # Fall back to best proposer content
            successful = [p["content"] for p in proposals if p["status"] == "success" and p["content"]]
            final_text = successful[0] if successful else f"Synthesis error: {e}"

        return {
            "final_synthesis": final_text,
            "proposals": proposals,
            "aggregator": active_aggregator,
        }
